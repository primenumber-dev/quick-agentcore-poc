// ----------------------------------------------------------------------------
// Output schema
// ----------------------------------------------------------------------------
const elementValueSchema = z.object({
  V: z
    .string()
    .describe(
      "値（常に文字列）。数値・日付・時刻・コード・空文字すべて文字列で入る。" +
        "ESコードに応じてパース方法を切り替える必要がある。"
    ),
  ES: z
    .string()
    .describe(
      "項目ステータスコード。値の意味（型・単位）を表す。" +
        "観測済みコード: " +
        "[正常] 000=数値, 04z=コード/略称, a4z=正式名称, 14z=空文字が正常, " +
        "003=千株単位, 004=出来高単位, 006=百万円単位, 008=億円単位, " +
        "010=前日比/変化量(符号付), 018=前日比億円単位, 00j=32分の1表示(米国債), " +
        "0T0=時刻HH:MM, 0TG=大引(値は'*大引'), 0TC=前引(値は'*前引'), " +
        "0D0=日付'(YY/MM/DD)', 0DA=期末'(YY/MM/末)', 0F0=年月'(YY/MM)'. " +
        "[NULL系] 100=値なし(一時的), 1T0=時刻なし, 1D0=日付なし, " +
        "Azz=集計対象外（仕様上その銘柄では存在しない）。" +
        "100とAzzの違い: 100は将来取れる可能性、Azzは恒久的に取れない。" +
        "上記以外のコードが返る可能性もある。"
    ),
});

const outputSchema = {
  S: z
    .string()
    .describe("応答全体ステータス。空文字=正常、'I0001'=入力エラー（ErrR参照）"),
  OD: z
    .string()
    .describe("データ取得日時（JST、'YYYY/MM/DD hh:mm:ss'）"),
  D: z
    .record(
      z.string(),
      z.object({
        MS: z
          .string()
          .describe(
            "銘柄ステータス。'A00'=正常、'A13'=指定された銘柄コードが存在しない（部分失敗）。他のMSコードもありえる。"
          ),
        E: z
          .record(z.string(), elementValueSchema)
          .describe("Element別の値。キーはリクエストの ECs に対応"),
      })
    )
    .optional()
    .describe(
      "銘柄ごとのデータ。キーはQuoteコード（リクエストのQCsに対応）。" +
        "存在しない銘柄もMS=A13で含まれる（部分成功モデル）。エラー時は省略。"
    ),
  ErrR: z
    .array(z.string())
    .optional()
    .describe("エラーメッセージ配列。S が空文字以外のときに付与される。"),
};

// ----------------------------------------------------------------------------
// Tool registration
// ----------------------------------------------------------------------------
const description =
  "QUICK quoteElement.do APIを叩き、指定された銘柄群について指定された項目の現在値スナップショットを取得する。" +
  "国内株式・国内指数・海外指数・為替・先物・国内債券・海外債券・市場統計の全資産クラスに対応し、" +
  "1リクエストで資産クラスを跨いだ複数銘柄を一括取得できる（最大100銘柄）。" +
  "時系列データ（日足・週足・分足）が必要な場合はこのツールではなく get_price_history / get_intraday_history を使うこと。" +
  "ニュース検索は search_news、ランキングは get_ranking。" +
  "値はすべて文字列で返り、ES（項目ステータスコード）と組み合わせて意味を解釈する必要がある（outputSchema 参照）。" +
  "対応外Element・存在しないQuoteを指定してもAPIはエラーにせず、" +
  "MS=A13（銘柄なし）/ ES=Azz（集計対象外）/ レスポンス直下のECNDキー（存在しないElementコード）に部分失敗が振り分けられる形で返る。";

export function registerGetQuote(server: McpServer): void {
  server.registerTool(
    "get_quote",
    {
      title: "銘柄スナップショット取得",
      description,
      inputSchema,
      outputSchema,
    },
    async ({ QCs, ECs }) => {
      const result = await callQuickApi<Record<string, unknown>>(
        "quoteElement.do",
        { QCs, ECs }
      );
      return {
        content: [{ type: "text", text: JSON.stringify(result) }],
        structuredContent: result,
      };
    }
  );
}
